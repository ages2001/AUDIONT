#!/usr/bin/env python3
"""Generate drv/synthtab.h: waveforms, pitch and envelope tables for the FM synth."""
import numpy as np, os
OUT = os.path.join(os.path.dirname(__file__), '..', 'drv', 'synthtab.h')
FS = 48000
BLOCK = 32
N = 1024
t = np.arange(N) / N
waves = []
s = np.sin(2 * np.pi * t)
waves.append(s)                                   # 0 sine
waves.append(np.where(s > 0, s, 0) * 2 - 0.64)    # 1 half sine (DC removed)
waves.append(np.abs(s) * 2 - 1.27)                # 2 abs sine
waves.append(np.where((t % 0.5) < 0.25, np.sin(2 * np.pi * t), 0) * 2 - 0.32)  # 3 pulse sine
sq = sum(np.sin(2 * np.pi * k * t) / k for k in range(1, 16, 2)) * 4 / np.pi   # 4 band-limited square
waves.append(sq * 0.8)
saw = sum(((-1) ** (k + 1)) * np.sin(2 * np.pi * k * t) / k for k in range(1, 16)) * 2 / np.pi  # 5 saw
waves.append(saw * 0.8)
tri = sum(((-1) ** ((k - 1) // 2)) * np.sin(2 * np.pi * k * t) / (k * k) for k in range(1, 16, 2)) * 8 / np.pi ** 2
waves.append(tri)                                 # 6 triangle
w2 = np.sin(2 * np.pi * t) + 0.5 * np.sin(4 * np.pi * t) + 0.33 * np.sin(6 * np.pi * t)
waves.append(w2 / np.abs(w2).max())               # 7 organ-ish
wq = np.clip(np.round(np.array(waves) * 32767), -32767, 32767).astype(int)

notes = [int(round(440.0 * 2 ** ((n - 69) / 12.0) / FS * 2 ** 32)) for n in range(128)]
pow2 = [int(round(2 ** (i / 768.0) * 65536)) for i in range(769)]

def rtime(r):          # rate 0..127 -> seconds
    return 0.001 * 2 ** (r / 9.5)
decay = []             # Q30 multiplier per block reaching -60 dB in rtime
attack = []            # Q30 increment per block reaching 1.0 in rtime
for r in range(128):
    T = rtime(r)
    blocks = max(T * FS / BLOCK, 1)
    decay.append(int(round(10 ** (-3.0 / blocks) * (1 << 30))))
    attack.append(min(int(round((1 << 30) / blocks)), 1 << 30))
# velocity curve (Q15)
vel = [int(round((v / 127.0) ** 1.6 * 32767)) for v in range(128)]
# channel volume / expression curve (Q15), MIDI recommended 40*log10(v/127)
vol = [0] + [int(round(10 ** (40 * np.log10(v / 127.0) / 20) * 32767)) for v in range(1, 128)]
# pan law (Q15): constant power
pan = [(int(round(np.cos(p / 127.0 * np.pi / 2) * 32767)), int(round(np.sin(p / 127.0 * np.pi / 2) * 32767))) for p in range(128)]

def arr(name, ctype, vals, per=12):
    body = '\n'.join('    ' + ', '.join(str(v) for v in vals[i:i + per]) + ',' for i in range(0, len(vals), per))
    return 'static const %s %s[%d] = {\n%s\n};\n' % (ctype, name, len(vals), body)

src = '/* generated by tools/gensynth.py */\n#define SYN_WAVES %d\n#define SYN_WAVELEN %d\n#define SYN_BLOCK %d\n' % (len(wq), N, BLOCK)
src += 'static const short g_Wave[%d][%d] = {\n' % (len(wq), N)
for w in wq:
    src += '  {' + ','.join(str(v) for v in w) + '},\n'
src += '};\n'
src += arr('g_NoteInc', 'unsigned long', [str(v) + 'UL' for v in notes], 6)
src += arr('g_Pow2', 'unsigned long', pow2)
src += arr('g_DecayMul', 'unsigned long', [str(v) + 'UL' for v in decay], 6)
src += arr('g_AttackInc', 'unsigned long', [str(v) + 'UL' for v in attack], 6)
src += arr('g_VelCurve', 'unsigned short', vel)
src += arr('g_VolCurve', 'unsigned short', vol)
src += 'static const unsigned short g_PanTab[128][2] = {\n' + '\n'.join('  {%d,%d},' % p for p in pan) + '\n};\n'
open(OUT, 'w').write(src)
print('ok', len(src))
