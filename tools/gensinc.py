#!/usr/bin/env python3
"""Generate drv/sinctab.h: Kaiser windowed sinc for the polyphase resampler."""
import numpy as np, os
c, beta, zc, res = 0.91, 8.0, 8, 1024
x = np.arange(0, zc * res + 2) / float(res)
w = np.i0(beta * np.sqrt(np.clip(1 - (x / zc) ** 2, 0, 1))) / np.i0(beta)
h = c * np.sinc(c * x) * w
h[x >= zc] = 0
q = np.round(h * 16384).astype(int)
body = '\n'.join('    ' + ', '.join(str(v) for v in q[i:i + 16]) + ',' for i in range(0, len(q), 16))
out = ('/* generated by tools/gensinc.py: Kaiser(beta=%g) windowed sinc, cutoff %g, '
       'x = 0..%d step 1/%d, Q14 */\n#define SINC_RES %d\n#define SINC_ZC %d\n'
       'static const short g_SincTab[%d] = {\n%s\n};\n') % (beta, c, zc, res, res, zc, len(q), body)
open(os.path.join(os.path.dirname(__file__), '..', 'drv', 'sinctab.h'), 'w').write(out)
