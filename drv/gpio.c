/*
 * AUDIONT - GPIO pads of Intel PCHs / SoCs for the ACPI GpioIo lines of codecs
 * and amplifiers (enable, reset, shutdown).  Output only, polled.
 *
 * Sunrise Point and later ("pinctrl-intel" hardware): the controller device
 * (INT344B, INT34BB, INT34C5, INTC1057, ...) has one memory resource per pad
 * community; when the firmware fills those in at run time (_CRS methods), the
 * community lies at SBREG_BAR + (port id << 16) with SBREG_BAR from the DSDT
 * (SBRG) or the P2SB device.  ACPI pin numbers map to pads through the pad
 * groups of each community (tables generated from Linux drivers/pinctrl/intel,
 * the port ids from coreboot).  PADBAR in the community gives the pad
 * registers: PADCFG0 bit 0 is the output level, bit 8 disables the output.
 * Bay Trail (INT33FC) and Cherry Trail (INT33FF) have their own layouts.
 * Unknown controllers with one memory resource: pin = pad (Lunar Lake and
 * later, described by _DSD in the "Intel platform" binding).
 * AMD FCH GPIO (AMDI0030, AMD0030, AMDI0031; Linux pinctrl-amd): one 32-bit
 * register a pin at pin * 4: output value bit 22, output enable bit 23, pin
 * status (input level) bit 16.
 */
#include "codec.h"

typedef struct { USHORT Base, Size; SHORT GpioBase; } GPP;           /* GpioBase -1: no ACPI numbers */
typedef struct { UCHAR Bar; CHAR Com; USHORT PinBase, NPins; UCHAR NGpp; const GPP *Gpp; } COMM;
typedef struct { const char *Hid; UCHAR Uid; UCHAR Fam; const COMM *C; } SOC;   /* Uid 255: any */

/* generated by tools/gengpio.py from Linux drivers/pinctrl/intel */
#include "gpiotab.h"

#define FAM_SPT   1     /* port id 0xAF - community */
#define FAM_CNL   2     /* 0x6E - community (Cannon Lake .. Alder Lake, Jasper Lake) */
#define FAM_EHL   3     /* one device per community, _UID = community */
#define FAM_MTL   4
#define FAM_APL   5     /* one device per community by _UID */
#define FAM_GLK   6

#define PADBAR          0x0C
#define PADCFG0_TX      0x001
#define PADCFG0_RX      0x002
#define PADCFG0_TXDIS   0x100
#define PADCFG0_RXDIS   0x200
#define PADCFG0_PMODE   0x3C00

/* a controller: up to 8 mapped communities */
typedef struct {
    char    Name[5];
    UCHAR   Kind;               /* 1 pinctrl-intel, 2 Bay Trail, 3 Cherry Trail, 4 linear, 5 AMD */
    const COMM *C;              /* communities (kind 1) */
    const UCHAR *BytMap;
    ULONG   BytLen;
    PUCHAR  Va[8];
    ULONG   Pa[8], PadOff[8], PadSize[8];
    BOOLEAN Ok;
} GPIO_CTRL;

#define MAX_CTRL 8
static GPIO_CTRL g_Ctrl[MAX_CTRL];
static ULONG g_NCtrl;

/* SBREG_BAR: DSDT Name (SBRG, ...) or the P2SB BAR (P2SB hidden: unhide it for the read) */
static ULONG SbregBase(UCHAR fam)
{
    int t;
    ULONG dev = (fam == FAM_APL || fam == FAM_GLK) ? 0x0D : 0x1F, fn = (fam == FAM_APL || fam == FAM_GLK) ? 0 : 1;
    ULONG bar, hidden;
    for (t = 0; AcpiTable(t); t++) {
        const ACPI_TABLE *a = AcpiTable(t);
        ULONG i;
        if (a->Sig != ACPI_SIG('D', 'S', 'D', 'T') && a->Sig != ACPI_SIG('S', 'S', 'D', 'T')) continue;
        for (i = 36; i + 10 < a->Len; i++)
            if (a->Va[i] == 0x08 && !memcmp(a->Va + i + 1, "SBRG", 4) && a->Va[i + 5] == 0x0C) {
                bar = (ULONG)a->Va[i + 6] | ((ULONG)a->Va[i + 7] << 8) | ((ULONG)a->Va[i + 8] << 16) |
                      ((ULONG)a->Va[i + 9] << 24);
                if (bar && !(bar & 0xFFFFFF)) return bar;
            }
    }
    hidden = PciRead16(0, dev, fn, 0) == 0xFFFF;
    if (hidden) PciWrite8(0, dev, fn, 0xE1, 0);
    bar = PciRead32(0, dev, fn, 0x10) & ~0xFUL;
    if (PciRead32(0, dev, fn, 0x14)) bar = 0;                 /* above 4 GB: not reachable here */
    if (hidden) PciWrite8(0, dev, fn, 0xE1, 1);
    return (bar && bar != 0xFFFFFFF0UL) ? bar : 0;
}

static ULONG PortId(UCHAR fam, int com, ULONG uid)
{
    static const UCHAR mtl[6] = { 0xD1, 0xD2, 0, 0xD3, 0xD4, 0xD5 };
    static const UCHAR apl[5] = { 0, 0xC5, 0xC4, 0xC7, 0xC0 };
    static const UCHAR glk[5] = { 0, 0xC4, 0xC5, 0xC9, 0xC8 };
    switch (fam) {
    case FAM_SPT: return com >= 0 && com <= 3 ? 0xAF - com : 0;
    case FAM_CNL: return com >= 0 && com <= 5 ? 0x6E - com : 0;
    case FAM_EHL: return uid <= 5 ? 0x6E - uid : 0;
    case FAM_MTL: return com >= 0 && com <= 5 ? mtl[com] : 0;
    case FAM_APL: return uid <= 4 ? apl[uid] : 0;
    case FAM_GLK: return uid <= 4 ? glk[uid] : 0;
    }
    return 0;
}

typedef struct { const char *Name; AML_DEV Dev; BOOLEAN Found; } FIND_CTX;
static BOOLEAN FindByName(const AML_DEV *d, void *p)
{
    FIND_CTX *f = (FIND_CTX *)p;
    char hid[16];
    if (memcmp(d->Name, f->Name, 4)) return TRUE;
    AmlHid(d, hid, sizeof(hid));
    if (!hid[0]) return TRUE;
    f->Dev = *d;
    f->Found = TRUE;
    return FALSE;
}

static BOOLEAN MapComm(GPIO_CTRL *g, ULONG i, ULONG pa)
{
    PUCHAR va;
    ULONG rev, pad;
    if (!pa) return FALSE;
    va = (PUCHAR)OsMapMmio(pa, 0x10000);
    if (!va) return FALSE;
    rev = MMIO32(va, 0);
    pad = MMIO32(va, PADBAR);
    if (rev == 0xFFFFFFFF || !pad || pad >= 0x10000) {
        LOGI("gpio: %s community %u at %08x not present (%08x %08x)", g->Name, i, pa, rev, pad);
        OsUnmapMmio(va, 0x10000);
        return FALSE;
    }
    g->Va[i] = va; g->Pa[i] = pa; g->PadOff[i] = pad;
    g->PadSize[i] = ((rev >> 16) >= 0x092) ? 16 : 8;            /* PADCFG0..3 with debounce */
    return TRUE;
}

static GPIO_CTRL *OpenCtrl(const char *name)
{
    FIND_CTX f;
    GPIO_CTRL *g;
    AML_RES r;
    char hid[16];
    ULONGLONG uid = 0;
    ULONG i, n;
    for (i = 0; i < g_NCtrl; i++)
        if (!memcmp(g_Ctrl[i].Name, name, 4)) return g_Ctrl[i].Ok ? &g_Ctrl[i] : NULL;
    if (g_NCtrl >= MAX_CTRL) return NULL;
    g = &g_Ctrl[g_NCtrl++];
    memset(g, 0, sizeof(*g));
    memcpy(g->Name, name, 4);
    memset(&f, 0, sizeof(f));
    f.Name = name;
    AmlForEachDevice(FindByName, &f);
    if (!f.Found) { LOGE("gpio: controller %s not in the ACPI tables", name); return NULL; }
    AmlHid(&f.Dev, hid, sizeof(hid));
    AmlNamedInt(&f.Dev, "_UID", &uid);
    AmlResources(&f.Dev, &r);
    if (!strcmp_s(hid, "INT33FC") || !strcmp_s(hid, "INT33FF")) {
        ULONG len = r.NMem && r.MemLen[0] ? r.MemLen[0] : 0x8000;
        if (!r.NMem || !r.MemBase[0]) { LOGE("gpio: %s (%s) has no memory resource", name, hid); return NULL; }
        g->Kind = hid[5] == 'F' && hid[6] == 'C' ? 2 : 3;
        if (g->Kind == 2) {
            if (uid == 1) { g->BytMap = g_BytScore; g->BytLen = sizeof(g_BytScore); }
            else if (uid == 2) { g->BytMap = g_BytNcore; g->BytLen = sizeof(g_BytNcore); }
            else { g->BytMap = g_BytSus; g->BytLen = sizeof(g_BytSus); }
        }
        g->Pa[0] = r.MemBase[0];
        g->PadSize[0] = len > 0x10000 ? 0x10000 : len;
        g->Va[0] = (PUCHAR)OsMapMmio(g->Pa[0], g->PadSize[0]);
        g->Ok = g->Va[0] != NULL;
        LOGI("gpio: %s %s uid %u at %08x", name, hid, (ULONG)uid, g->Pa[0]);
        return g->Ok ? g : NULL;
    }
    if (!strcmp_s(hid, "AMDI0030") || !strcmp_s(hid, "AMD0030") || !strcmp_s(hid, "AMDI0031")) {
        ULONG len = r.NMem && r.MemLen[0] ? r.MemLen[0] : 0x400;
        if (!r.NMem || !r.MemBase[0]) { LOGE("gpio: %s (%s) has no memory resource", name, hid); return NULL; }
        g->Kind = 5;
        g->Pa[0] = r.MemBase[0];
        g->PadSize[0] = len > 0x2000 ? 0x2000 : len;
        g->Va[0] = (PUCHAR)OsMapMmio(g->Pa[0], g->PadSize[0]);
        g->Ok = g->Va[0] != NULL;
        LOGI("gpio: %s %s (AMD) at %08x", name, hid, g->Pa[0]);
        return g->Ok ? g : NULL;
    }
    /* Uid 255: one device for all communities; else one device per community (_UID) */
    for (i = 0; i < ARRAYSIZE(g_Socs); i++)
        if (!strcmp_s(g_Socs[i].Hid, hid) && (g_Socs[i].Uid == 255 || g_Socs[i].Uid == uid)) break;
    if (i < ARRAYSIZE(g_Socs)) {
        const SOC *soc = &g_Socs[i];
        ULONG sbreg = 0;
        g->Kind = 1;
        g->C = soc->C;
        for (n = 0; soc->C[n].Bar != 0xFF && n < 8; n++) {
            ULONG bar = soc->C[n].Bar, pa = bar < r.NMem ? r.MemBase[bar] : 0, pid;
            int com = soc->C[n].Com;
            if (soc->Fam == FAM_SPT && com < 0) com = n == 2 ? 3 : (int)n;   /* Sunrise Point-LP: COM0, 1, 3 */
            if (!pa && (pid = PortId(soc->Fam, com, (ULONG)uid))) {
                if (!sbreg) sbreg = SbregBase(soc->Fam);
                if (sbreg) pa = sbreg + (pid << 16);
            }
            if (MapComm(g, n, pa)) g->Ok = TRUE;
        }
        LOGI("gpio: %s %s uid %u: %u communities%s", name, hid, (ULONG)uid, n, g->Ok ? "" : ", none reachable");
        return g->Ok ? g : NULL;
    }
    /* unknown: one community, pin = pad */
    if (r.NMem == 1 && r.MemBase[0] && MapComm(g, 0, r.MemBase[0])) {
        g->Kind = 4;
        g->Ok = TRUE;
        LOGI("gpio: %s %s: unknown controller, pins taken as pads", name, hid);
        return g;
    }
    LOGE("gpio: %s %s: controller not supported", name, hid);
    return NULL;
}

BOOLEAN GpioResolve(const AML_GPIO *a, GPIO_PIN *p)
{
    GPIO_CTRL *g;
    ULONG pin = a->Pin, n, k;
    memset(p, 0, sizeof(*p));
    memcpy(p->Ctrl, a->Ctrl, 4);
    p->Pin = a->Pin;
    if (!a->Ctrl[0] || !(g = OpenCtrl(a->Ctrl))) return FALSE;
    switch (g->Kind) {
    case 2:                                                   /* Bay Trail: 16 bytes a pad, VAL at +8 */
        if (pin >= g->BytLen) return FALSE;
        p->Cfg = g->Va[0] + g->BytMap[pin] * 16 + 8;
        break;
    case 3:                                                   /* Cherry Trail: families of 15 pads */
        if (0x4400 + (pin / 15) * 0x400 + (pin % 15) * 8 + 8 > g->PadSize[0]) return FALSE;
        p->Cfg = g->Va[0] + 0x4400 + (pin / 15) * 0x400 + (pin % 15) * 8;
        break;
    case 4:
        p->Cfg = g->Va[0] + g->PadOff[0] + pin * g->PadSize[0];
        break;
    case 5:
        if (pin * 4 + 4 > g->PadSize[0]) return FALSE;
        p->Cfg = g->Va[0] + pin * 4;
        break;
    default:
        for (n = 0; g->C[n].Bar != 0xFF && n < 8; n++) {
            const COMM *c = &g->C[n];
            for (k = 0; k < c->NGpp; k++) {
                const GPP *gp = &c->Gpp[k];
                if (gp->GpioBase < 0 || pin < (ULONG)gp->GpioBase || pin >= (ULONG)gp->GpioBase + gp->Size) continue;
                if (!g->Va[n]) return FALSE;
                p->Pad = gp->Base + (pin - gp->GpioBase) - c->PinBase;
                p->Cfg = g->Va[n] + g->PadOff[n] + p->Pad * g->PadSize[n];
                return TRUE;
            }
        }
        LOGI("gpio: %s pin %u not in any pad group", g->Name, pin);
        return FALSE;
    }
    p->Pad = pin;
    return TRUE;
}

static UCHAR KindOf(const GPIO_PIN *p)
{
    ULONG i;
    for (i = 0; i < g_NCtrl; i++) if (!memcmp(g_Ctrl[i].Name, p->Ctrl, 4)) return g_Ctrl[i].Kind;
    return 0;
}

void GpioSet(GPIO_PIN *p, BOOLEAN high)
{
    ULONG v;
    if (!p || !p->Cfg) return;
    v = MMIO32(p->Cfg, 0);
    switch (KindOf(p)) {
    case 2:                                                   /* VAL: bit 1 output disable (active low) */
        v = (v & ~2UL & ~1UL) | (high ? 1 : 0);
        break;
    case 3:                                                   /* PADCTRL0: GPIOEN 15, GPIOCFG 8-10 = GPO */
        v = (v & ~(0x700UL | 2UL)) | 0x8000UL | 0x100UL | (high ? 2 : 0);
        break;
    case 5:                                                   /* AMD: OUTPUT_VALUE 22, OUTPUT_ENABLE 23 */
        v = (v & ~(1UL << 22)) | (1UL << 23) | (high ? (1UL << 22) : 0);
        break;
    default:
        v = (v & ~(PADCFG0_PMODE | PADCFG0_TXDIS | PADCFG0_TX)) | (high ? PADCFG0_TX : 0);
        break;
    }
    MMIO32(p->Cfg, 0) = v;
    LOGV("gpio: %s pin %u -> %u (%08x)", p->Ctrl, p->Pin, high ? 1 : 0, MMIO32(p->Cfg, 0));
}

int GpioGet(GPIO_PIN *p)
{
    ULONG v;
    if (!p || !p->Cfg) return -1;
    v = MMIO32(p->Cfg, 0);
    switch (KindOf(p)) {
    case 2: return (int)(v & 1);
    case 3: return (int)(v & 1);
    case 5: return (v & (1UL << 16)) ? 1 : 0;                 /* PIN_STS */
    default: return (v & PADCFG0_RX) ? 1 : 0;
    }
}

void GpioCloseAll(void)
{
    ULONG i, n;
    for (i = 0; i < g_NCtrl; i++)
        for (n = 0; n < 8; n++)
            if (g_Ctrl[i].Va[n]) OsUnmapMmio(g_Ctrl[i].Va[n], (g_Ctrl[i].Kind >= 2 && g_Ctrl[i].Kind <= 3) ||
                                                              g_Ctrl[i].Kind == 5 ? g_Ctrl[i].PadSize[0] : 0x10000);
    memset(g_Ctrl, 0, sizeof(g_Ctrl));
    g_NCtrl = 0;
}
