/*
 * AUDIONT - Realtek RT1320 / RT1321 SoundWire smart amplifiers (SDCA class, internal DSP),
 * Linux sound/soc/codecs/rt1320-sdw.c.
 *
 *   DP1 (2 channels) -> PPU21 (posture: channel select) -> FU21 -> OT23 L / R
 *   power domain PDE23 (amplifier); DP4 (AEC), DP8 / DP10 (microphone function 2): not used
 *
 * The chip has an MCU and a HiFi DSP.  Linux runs it without any firmware file: the MCU patch
 * (realtek/rt1320/rt1320-patch-code-*.bin) is optional - when request_firmware fails,
 * rt1320_load_mcu_patch writes a 4-byte stub (0x00008067, a RISC-V "ret") at the patch entry and
 * clears 0xc598 instead, and the DSP firmware (realtek,dspfw-name / "DSP FW Update") and the RAE
 * parameters are only loaded on request.  This driver does what Linux does without the files:
 * the stub, no DSP download, no R0 calibration (the speaker protection then uses the ROM
 * defaults).
 *
 * Init (rt1320_io_init): chip id (0xc404 version, 0xc405 / 0xc406 device id; RT1321: the HV id
 * through the 0xc480 private-register window decides VA0 / VA1, version 1 is VA2), the preset
 * table of that silicon (rt1320_vab_preset / rt1320_vc_preset / rt1321_preset: the MCU patch at
 * its entry in the table, the KR0 ready wait before PDE23 -> PS0 on VC, the Actual_PS wait after
 * each PDE23 write), Function_Status cleared, the bus clock dependent 0xc600..0xc603
 * (rt1320_bus_config), CS21 at 48 kHz, FU21 0 dB and muted, PDE23 PS3.  Posture PPU21
 * ("RX Channel Select": 0 "L,R", 2 "L,L", 3 "R,R"): one amplifier plays L,R, with two or more
 * the even Index L,L and the odd R,R.  Stream: DAPM supply "PDE 23" first (PS0, Actual_PS
 * polled), then the OT23 L / R autodisable switches (FU21 unmuted); off in reverse.
 * The RT1320 VA / VB distinction (DSP ROM version read with PDE23 on) only selects firmware
 * file names in Linux and is not done.
 */
