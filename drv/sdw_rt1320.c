static BOOLEAN Probe(SDW_DEV *d)
{
    d->Kind = SDW_KIND_AMP;
    d->Play.Num = 1; d->Play.Ch = 2; d->Play.Type = SDW_DP_FULL; d->Play.CpSm = FALSE;   /* simple_ch_prep_sm */
    memset(&d->Rec, 0, sizeof(d->Rec));                 /* DP4 / DP8 / DP10 not used */
    d->Paging = TRUE;
    return TRUE;
}

static ULONG Rd(SDW_DEV *d, ULONG reg)
{
    UCHAR v = 0;
    SdwRead(d, reg, &v);
    return v;
}

/* rt1320_pr_read: a 32-bit private register through the 0xc480 window */
static ULONG PrRead(SDW_DEV *d, ULONG reg)
{
    SdwWrite(d, 0xc483, 0x80);
    SdwWrite(d, 0xc482, 0x40);
    SdwWrite(d, 0xc481, 0x0c);
    SdwWrite(d, 0xc480, 0x10);
    SdwWrite(d, 0xc487, (UCHAR)(reg >> 24));
    SdwWrite(d, 0xc486, (UCHAR)(reg >> 16));
    SdwWrite(d, 0xc485, (UCHAR)(reg >> 8));
    SdwWrite(d, 0xc484, (UCHAR)reg);
    SdwWrite(d, 0xc482, 0xc0);
    return (Rd(d, 0xc48f) << 24) | (Rd(d, 0xc48e) << 16) | (Rd(d, 0xc48d) << 8) | Rd(d, 0xc48c);
}

/* rt1320_pde_transition_delay: Actual_PS polled for up to 2 s */
static void PdeWait(SDW_DEV *d, ULONG ps)
{
    ULONG t;
    for (t = 0; t < 2000; t++) {
        if (Rd(d, SDW_SDCA_CTL(FN_AMP, ENT_PDE23, SDCA_CTL_PDE_ACTUAL_PS, 0)) == ps) return;
        SdwDelay(1);
    }
    LOGI("sdw: %s: PDE23 to PS%u is not ready", d->Name, ps);
}

/* rt1320_load_mcu_patch without the patch file */
static void McuPatch(SDW_DEV *d)
{
    ULONG base;
    if (d->Priv[P_ID] == RT1321_ID) {
        if (d->Priv[P_VER] == 2) return;                /* VA2: no patch */
        base = 0x10008000;
    } else base = 0x10007000;
    SdwWrite(d, 0xc598, 0x00);
    SdwWrite(d, base, 0x67);
    SdwWrite(d, base + 1, 0x80);
    SdwWrite(d, base + 2, 0x00);
    SdwWrite(d, base + 3, 0x00);
    if (d->Priv[P_ID] == RT1321_ID) {
        SdwWrite(d, 0xd73c, 0x67);
        SdwWrite(d, 0xd73d, 0x80);
        SdwWrite(d, 0xd73e, 0x00);
        SdwWrite(d, 0xd73f, 0x00);
    }
}

/* rt1320_vab_preset / rt1320_vc_preset / rt1321_preset */
static void Preset(SDW_DEV *d, const ULONG *t, ULONG n, ULONG patchAt, BOOLEAN kr0)
{
    ULONG i, k;
    for (i = 0; i < n; i++) {
        ULONG reg = t[2 * i];
        UCHAR val = (UCHAR)t[2 * i + 1];
        if (reg == patchAt) McuPatch(d);
        if (kr0 && reg == PDE23_REQ && val == 0) {
            for (k = 0; k < 200 && Rd(d, KR0_INT_READY) != 0x1f; k++) SdwDelay(1);
            if (k == 200) LOGI("sdw: %s: MCU not ready (KR0_INT_READY %02x)", d->Name, Rd(d, KR0_INT_READY));
        }
        SdwWrite(d, reg, val);
        if (reg == PDE23_REQ) PdeWait(d, val);
    }
}

/* rt1320_bus_config: by SCP_BUS_CLOCK_BASE (set by the bus core for SDCA-class parts) */
static void BusConfig(SDW_DEV *d)
{
    static const ULONG c24[] = { 0xc600, 0x04, 0xc601, 0x83, 0xc602, 0x1f, 0xc603, 0x40 };
    static const ULONG c22[] = { 0xc600, 0x07, 0xc601, 0x80, 0xc602, 0x0f, 0xc603, 0x40 };
    ULONG base = Rd(d, SDW_SCP_BUS_CLOCK_BASE);
    if (base == 1 || base == 2) SdwSeq(d, c24, 4);      /* 19.2 / 24 MHz */
    else if (base == 3 || base == 4) SdwSeq(d, c22, 4); /* 24.576 / 22.5792 MHz */
    else LOGI("sdw: %s: clock base %u, 0xc600 not set", d->Name, base);
}

static BOOLEAN Init(SDW_DEV *d)
{
    ULONG e0 = d->Errors, ver, id, hv, st;
    UCHAR sel = 0, v;                                   /* "L,R" */
    char rev[4];
    if (!SdwRead(d, DEV_VERSION_ID_1, &v)) return FALSE;
    ver = v;
    id = (Rd(d, DEV_ID_0) << 8) | Rd(d, DEV_ID_1);
    /* "a workaround that reads the value twice to obtain the correct result" */
    PrRead(d, HV_DEV_ID_0); PrRead(d, HV_DEV_ID_1);
    hv = ((PrRead(d, HV_DEV_ID_0) & 0xFF) << 8) | (PrRead(d, HV_DEV_ID_1) & 0xFF);
    d->Priv[P_ID] = id;
    if (id == RT1321_ID) {
        if (ver == 1) d->Priv[P_VER] = 2;
        else if (hv == RT1321_HV_VA0) d->Priv[P_VER] = 0;
        else if (hv == RT1321_HV_VA1) d->Priv[P_VER] = 1;
        else d->Priv[P_VER] = 0xFF;
    } else d->Priv[P_VER] = ver;
    st = Rd(d, SDW_SDCA_CTL(FN_AMP, ENT0, CTL_FUNC_STATUS, 0));
    /* like Linux, an unknown id / version gets no preset (an error message) and is run as it is */
    if (id == RT1320_ID && ver < 2) Preset(d, g_Rt1320Vab, ARRAYSIZE(g_Rt1320Vab) / 2, 0x3fc2bfc7, FALSE);
    else if (id == RT1320_ID) Preset(d, g_Rt1320Vc, ARRAYSIZE(g_Rt1320Vc) / 2, 0x3fc2bf83, TRUE);
    else if (id != RT1321_ID) LOGE("sdw: %s: unknown device id %04x (version %u): no preset", d->Name, id, ver);
    else if (d->Priv[P_VER] == 0) Preset(d, g_Rt1321Va0, ARRAYSIZE(g_Rt1321Va0) / 2, 0x1000cd56, FALSE);
    else if (d->Priv[P_VER] == 1) Preset(d, g_Rt1321Va1, ARRAYSIZE(g_Rt1321Va1) / 2, 0x1000cd56, FALSE);
    else if (d->Priv[P_VER] == 2) Preset(d, g_Rt1321Va2, ARRAYSIZE(g_Rt1321Va2) / 2, 0x1000cd56, FALSE);
    else LOGE("sdw: %s: RT1321 of unknown version %u (HV id %04x): no preset", d->Name, ver, hv);
    SdwWrite(d, SDW_SDCA_CTL(FN_AMP, ENT0, CTL_FUNC_STATUS, 0), FUNC_NEEDS_INIT);  /* write 1 to clear */
    BusConfig(d);
    SdcaRate(d, FN_AMP, ENT_CS21, RATE_48000);
    if (d->Count >= 2) sel = (d->Index & 1) ? 3 : 2;    /* "R,R" / "L,L" */
    SdwWrite(d, SDW_SDCA_CTL(FN_AMP, ENT_PPU21, CTL_POSTURE, 0), sel);
    SdcaVolume(d, FN_AMP, ENT_FU21, SDCA_CTL_FU_VOLUME, 3, 0);   /* 0 dB (the mbq default) */
    SdcaMute(d, FN_AMP, ENT_FU21, 3, TRUE);
    SdcaPower(d, FN_AMP, ENT_PDE23, SDCA_PS3, 0);
    rev[0] = 'A'; rev[1] = rev[2] = rev[3] = 0;
    if (id == RT1321_ID) rev[1] = d->Priv[P_VER] < 10 ? (char)('0' + d->Priv[P_VER]) : '?';
    else rev[0] = (char)('A' + MIN(d->Priv[P_VER], 25));
    LOGI("sdw: %s: %s V%s (id %04x, version %u, HV id %04x, function status %02x), MCU patch stub, no DSP firmware, "
         "%s (amplifier %u of %u), %u bus errors in init", d->Name, id == RT1321_ID ? "RT1321" : "RT1320", rev, id, ver,
         hv, st, sel == 3 ? "R,R" : sel == 2 ? "L,L" : "L,R", d->Index, d->Count, d->Errors - e0);
    return d->Errors - e0 < 8;
}

static void Stream(SDW_DEV *d, BOOLEAN rec, BOOLEAN on)
{
    if (rec) return;
    if (on) {
        SdwWrite(d, PDE23_REQ, SDCA_PS0);
        PdeWait(d, SDCA_PS0);
        SdcaMute(d, FN_AMP, ENT_FU21, 3, FALSE);
    } else {
        SdcaMute(d, FN_AMP, ENT_FU21, 3, TRUE);
        SdwWrite(d, PDE23_REQ, SDCA_PS3);
        PdeWait(d, SDCA_PS3);
    }
}

static void Shutdown(SDW_DEV *d)
{
    if (!d->Ready) return;
    SdcaMute(d, FN_AMP, ENT_FU21, 3, TRUE);
    SdwWrite(d, PDE23_REQ, SDCA_PS3);
    PdeWait(d, SDCA_PS3);
}

