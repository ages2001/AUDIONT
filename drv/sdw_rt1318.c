/*
 * AUDIONT - Realtek RT1318 SoundWire smart amplifier (SDCA class), Linux
 * sound/soc/codecs/rt1318-sdw.c.
 *
 *   DP1 (2 channels) -> UDMPU21 (channel select) -> FU21 -> class D -> SPOL / SPOR
 *   power domain PDE23 (amplifier); DP2 (I/V feedback) is not used
 *
 * Init: rt1318_io_init (the blind-write table; Linux does no software reset
 * on this part), CS21 to the 48 kHz index (hw_params), FU21 muted, PDE23 in
 * PS3.  The UDMPU21 cluster ("RX Channel Select": 0 "L,R", 1 "L,L", 5 "R,R")
 * selects the channel: one amplifier plays L,R; with two or more the even
 * Index plays L,L and the odd one R,R.  Stream: DAPM order of the Linux
 * driver - the DAC switch (FU21 unmute) powers before the CLASS D PGA, whose
 * POST_PMU puts PDE23 in PS0; off: PRE_PMD PDE23 PS3, then FU21 muted.
 * No volume control (Linux has none for this part: software volume).
 */
#include "sdw.h"

#define FN_AMP          0x04            /* FUNC_NUM_SMART_AMP */
#define ENT_UDMPU21     0x02
#define ENT_FU21        0x03
#define ENT_CS21        0x21
#define ENT_PDE23       0x31
#define CTL_UDMPU_CLUSTER 0x10
#define RATE_48000      0x09            /* RT1318_SDCA_RATE_48000HZ */

