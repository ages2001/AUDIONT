static BOOLEAN Probe(SDW_DEV *d)
{
    d->Kind = SDW_KIND_AMP;
    d->Play.Num = 1; d->Play.Ch = 2; d->Play.Type = SDW_DP_FULL; d->Play.CpSm = FALSE;   /* simple_ch_prep_sm */
    memset(&d->Rec, 0, sizeof(d->Rec));                 /* DP2 I/V feedback not used */
    d->Paging = TRUE;
    return TRUE;
}

static BOOLEAN Init(SDW_DEV *d)
{
    ULONG e0 = d->Errors;
    UCHAR sel = 0;                                      /* "L,R" */
    if (!SdwSeq(d, g_Blind, ARRAYSIZE(g_Blind) / 2) && d->Errors - e0 > 8) return FALSE;
    if (d->Count >= 2) sel = (d->Index & 1) ? 5 : 1;    /* "R,R" / "L,L" */
    SdwWrite(d, SDW_SDCA_CTL(FN_AMP, ENT_UDMPU21, CTL_UDMPU_CLUSTER, 0), sel);
    SdcaRate(d, FN_AMP, ENT_CS21, RATE_48000);
    SdcaMute(d, FN_AMP, ENT_FU21, 3, TRUE);
    SdcaPower(d, FN_AMP, ENT_PDE23, SDCA_PS3, 0);
    LOGI("sdw: %s: RT1318 %s (amplifier %u of %u), %u bus errors in init", d->Name,
         d->Count >= 2 ? ((d->Index & 1) ? "R,R" : "L,L") : "L,R", d->Index, d->Count, d->Errors - e0);
    return d->Errors - e0 < 8;
}

static void Stream(SDW_DEV *d, BOOLEAN rec, BOOLEAN on)
{
    if (rec) return;
    if (on) {
        SdcaMute(d, FN_AMP, ENT_FU21, 3, FALSE);
        SdcaPower(d, FN_AMP, ENT_PDE23, SDCA_PS0, 0);
    } else {
        SdcaPower(d, FN_AMP, ENT_PDE23, SDCA_PS3, 0);
        SdcaMute(d, FN_AMP, ENT_FU21, 3, TRUE);
    }
}

static void Shutdown(SDW_DEV *d)
{
    if (!d->Ready) return;
    SdcaPower(d, FN_AMP, ENT_PDE23, SDCA_PS3, 0);
    SdcaMute(d, FN_AMP, ENT_FU21, 3, TRUE);
}

static const USHORT g_Parts[] = { 0x1318, 0 };
const SDW_DRV g_SdwRt1318 = { "RT1318", 0x025D, g_Parts, SDW_KIND_AMP, Probe, Init, Stream, Shutdown };
